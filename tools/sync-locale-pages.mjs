/**
 * Generates the per-language pages and the sitemap.
 *
 * index.html and case-study.html are the templates for both languages. This
 * tool writes ko/ copies of them and stamps a static <head> block into all
 * four files, taken from the head sections of i18n/en.js and i18n/ko.js.
 *
 * Why the head is static rather than injected at runtime: the things that
 * read it cannot run JavaScript. LinkedIn, Slack and KakaoTalk preview bots
 * never execute scripts, so runtime Open Graph tags were invisible to them;
 * Google wants hreflang in the served HTML, an HTTP header, or the sitemap,
 * not from a script; Bing and Naver largely do not render JS at all. The
 * body is still rendered client-side - that is a separate problem - but the
 * head no longer depends on a script running.
 *
 * ko/ exists because Vercel consults the filesystem before any rewrite, so a
 * real ko/index.html removes the routing question entirely. The two copies
 * differ ONLY inside the generated block and in <html lang>; everything that
 * can drift in behaviour stays in the shared part of the template.
 *
 *   node tools/sync-locale-pages.mjs          regenerate ko/ + head + sitemap
 *   node tools/sync-locale-pages.mjs --check  fail if any output is stale
 *
 * Run it after editing either template or the head section of a copy file.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const ORIGIN = 'https://stevejung.dev';
const DEFAULT_LOCALE = 'en';
const OUT = 'ko';

// Link-preview card image. Captured from the hero at exactly these dimensions
// (tools/README notes how); the declared width and height must keep matching
// the file, or the crawlers that trust them lay the card out wrong.
const OG_IMAGE = { path: '/og-image.png', width: 1200, height: 630 };

// One Person entity for the whole site, so search engines can tie the pages,
// the job title and the LinkedIn profile to the same person.
const PERSON = {
  '@context': 'https://schema.org',
  '@type': 'Person',
  name: 'Steve Jung',
  jobTitle: 'Product Designer & Creative Technologist',
  url: ORIGIN,
  sameAs: ['https://www.linkedin.com/in/stevejung-dev/'],
  knowsAbout: ['UX Design', 'Product Design', 'Front-End Development',
               'AI-Powered Automation', 'React', 'Figma']
};

// file -> the head key in i18n/<locale>.js and the path it is served at
const PAGES = [
  { file: 'index.html', key: 'index', route: '/' },
  { file: 'case-study.html', key: 'caseStudy', route: '/case-study' }
];

const START = '<!-- i18n:head:start -->';
const END = '<!-- i18n:head:end -->';
const LD_START = '<!-- i18n:jsonld:start -->';
const LD_END = '<!-- i18n:jsonld:end -->';

const check = process.argv.includes('--check');

// ---------------------------------------------------------------- copy data

/** Read window.SITE_COPY out of the locale files without a bundler. */
function loadCopy() {
  const win = {};
  const prev = globalThis.window;
  globalThis.window = win;
  try {
    for (const locale of ['en', 'ko']) {
      const src = fs.readFileSync(path.join(root, 'i18n', `${locale}.js`), 'utf8');
      new Function(src)();
    }
  } finally {
    globalThis.window = prev;
  }
  const copy = win.SITE_COPY;
  if (!copy || !copy.en || !copy.ko) throw new Error('i18n: SITE_COPY.en / .ko not found');
  return copy;
}

// ------------------------------------------------------------------- output

const esc = (s) => String(s)
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;');

/** The URL a page is served at in a given language. */
function href(route, locale) {
  const prefix = locale === DEFAULT_LOCALE ? '' : `/${locale}`;
  if (route === '/') return `${ORIGIN}${prefix || '/'}`;
  return `${ORIGIN}${prefix}${route}`;
}

function headBlock(head, route, locale) {
  const enHref = href(route, 'en');
  const koHref = href(route, 'ko');
  const self = locale === 'ko' ? koHref : enHref;
  const ogLocale = locale === 'ko' ? 'ko_KR' : 'en_US';
  const ogAlt = locale === 'ko' ? 'en_US' : 'ko_KR';
  const title = esc(head.title);
  const desc = esc(head.description);

  return [
    START,
    '<!-- Generated by tools/sync-locale-pages.mjs from i18n/<locale>.js — do not edit by hand. -->',
    `<title>${title}</title>`,
    `<meta name="description" content="${desc}">`,
    `<link rel="canonical" href="${self}">`,
    `<link rel="alternate" hreflang="en" href="${enHref}">`,
    `<link rel="alternate" hreflang="ko" href="${koHref}">`,
    `<link rel="alternate" hreflang="x-default" href="${enHref}">`,
    '<meta property="og:type" content="website">',
    '<meta property="og:site_name" content="Steve Jung">',
    `<meta property="og:url" content="${self}">`,
    `<meta property="og:title" content="${title}">`,
    `<meta property="og:description" content="${desc}">`,
    `<meta property="og:locale" content="${ogLocale}">`,
    `<meta property="og:locale:alternate" content="${ogAlt}">`,
    `<meta property="og:image" content="${ORIGIN}${OG_IMAGE.path}">`,
    `<meta property="og:image:width" content="${OG_IMAGE.width}">`,
    `<meta property="og:image:height" content="${OG_IMAGE.height}">`,
    '<meta name="twitter:card" content="summary_large_image">',
    `<meta name="twitter:title" content="${title}">`,
    `<meta name="twitter:description" content="${desc}">`,
    `<meta name="twitter:image" content="${ORIGIN}${OG_IMAGE.path}">`,
    END
  ].join('\n');
}

function jsonLdBlock() {
  return [
    LD_START,
    '<!-- Generated by tools/sync-locale-pages.mjs — do not edit by hand. -->',
    '<script type="application/ld+json">',
    JSON.stringify(PERSON, null, 2),
    '</script>',
    LD_END
  ].join('\n');
}

/** Replace the region between a marker pair with freshly generated content. */
function fill(src, start, end, body, file) {
  const s = src.indexOf(start);
  const e = src.indexOf(end);
  if (s < 0 || e < 0) throw new Error(`${file}: missing ${start} / ${end} markers`);
  return src.slice(0, s) + body + src.slice(e + end.length);
}

/** Swap in the generated blocks and set <html lang> for the target language. */
function render(template, head, route, locale, file) {
  let out = fill(template, START, END, headBlock(head, route, locale), file);
  out = fill(out, LD_START, LD_END, jsonLdBlock(), file);
  return out;
}

function sitemap() {
  const rows = [];
  for (const { route } of PAGES) {
    for (const locale of ['en', 'ko']) {
      rows.push([
        '  <url>',
        `    <loc>${href(route, locale)}</loc>`,
        `    <xhtml:link rel="alternate" hreflang="en" href="${href(route, 'en')}"/>`,
        `    <xhtml:link rel="alternate" hreflang="ko" href="${href(route, 'ko')}"/>`,
        `    <xhtml:link rel="alternate" hreflang="x-default" href="${href(route, 'en')}"/>`,
        '  </url>'
      ].join('\n'));
    }
  }
  // No <lastmod>: a value this tool cannot compute accurately is worse than
  // none, and Google ignores lastmod it finds unreliable.
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Generated by tools/sync-locale-pages.mjs — do not edit by hand. -->',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"',
    '        xmlns:xhtml="http://www.w3.org/1999/xhtml">',
    ...rows,
    '</urlset>',
    ''
  ].join('\n');
}

function robots() {
  return [
    '# Static portfolio — everything is public.',
    'User-agent: *',
    'Allow: /',
    '',
    `Sitemap: ${ORIGIN}/sitemap.xml`,
    ''
  ].join('\n');
}

// -------------------------------------------------------------------- write

const copy = loadCopy();
const outputs = [];

for (const { file, key, route } of PAGES) {
  const template = fs.readFileSync(path.join(root, file), 'utf8');
  for (const locale of ['en', 'ko']) {
    const head = (copy[locale].head || {})[key];
    if (!head || !head.title || !head.description) {
      throw new Error(`i18n/${locale}.js: head.${key} needs a title and a description`);
    }
    const out = render(template, head, route, locale, file)
      .replace(/<html(?:\s[^>]*)?>/, `<html lang="${locale}">`);
    outputs.push({ rel: locale === DEFAULT_LOCALE ? file : `${OUT}/${file}`, body: out });
  }
}
outputs.push({ rel: 'sitemap.xml', body: sitemap() });
outputs.push({ rel: 'robots.txt', body: robots() });

const stale = [];
for (const { rel, body } of outputs) {
  const dst = path.join(root, rel);
  const same = fs.existsSync(dst) && fs.readFileSync(dst, 'utf8') === body;
  if (check) {
    if (!same) stale.push(rel);
  } else if (!same) {
    fs.mkdirSync(path.dirname(dst), { recursive: true });
    fs.writeFileSync(dst, body);
    console.log(`updated ${rel}`);
  }
}

if (check) {
  if (stale.length) {
    console.error(
      'Generated files are out of date: ' + stale.join(', ') +
      '\nRun: node tools/sync-locale-pages.mjs'
    );
    process.exit(1);
  }
  console.log(`${outputs.length} generated files are up to date`);
} else {
  console.log(`in sync (${outputs.length} files)`);
}
